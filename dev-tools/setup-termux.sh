#!/usr/bin/env bash
# Free, no-root build setup for JAScanner on Termux (aarch64 Android).
# Uses only no-cost components: Termux packages, the checked-in Gradle wrapper,
# Android SDK command-line tools and the SDK platform/build-tools packages.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX_DIR="${PREFIX:-/data/data/com.termux/files/usr}"
HOME_DIR="${HOME:-/data/data/com.termux/files/home}"
ANDROID_SDK_DIR="${ANDROID_SDK_DIR:-$HOME_DIR/android-sdk}"
CMDLINE_TOOLS_REVISION="${CMDLINE_TOOLS_REVISION:-13114758}" # command-line tools 19.0
TMP_DIR="${TMPDIR:-$PREFIX_DIR/tmp}"
ZIP_PATH="$TMP_DIR/commandlinetools-linux-${CMDLINE_TOOLS_REVISION}_latest.zip"
SDKMANAGER="$ANDROID_SDK_DIR/cmdline-tools/latest/bin/sdkmanager"
GRADLE_PROPERTIES="$HOME_DIR/.gradle/gradle.properties"

if [[ ! -d "$PREFIX_DIR/share/termux" && ! -x "$PREFIX_DIR/bin/pkg" ]]; then
  echo "This script is meant for Termux (no pkg found at $PREFIX_DIR/bin/pkg)." >&2
  exit 1
fi

# Gradle and sdkmanager both need a JDK; Termux's openjdk-21 is free.
export JAVA_HOME="${JAVA_HOME:-$PREFIX_DIR/lib/jvm/java-21-openjdk}"
export PATH="$JAVA_HOME/bin:$PREFIX_DIR/bin:$PATH"

echo "==> Installing Termux packages (openjdk-21, aapt2, curl, unzip)"
pkg install -y openjdk-21 aapt2 curl unzip

echo "==> Installing Android SDK command-line tools into $ANDROID_SDK_DIR"
mkdir -p "$TMP_DIR" "$ANDROID_SDK_DIR/cmdline-tools"
if [[ ! -x "$SDKMANAGER" ]]; then
  url="https://dl.google.com/android/repository/commandlinetools-linux-${CMDLINE_TOOLS_REVISION}_latest.zip"
  # Downloads on mobile networks can drop; resume until the ZIP verifies.
  until [[ -s "$ZIP_PATH" ]] && unzip -tq "$ZIP_PATH" >/dev/null 2>&1; do
    echo "Downloading $url"
    curl -fL --retry 5 --retry-delay 2 -C - -o "$ZIP_PATH" "$url" || true
  done
  extract_dir="$TMP_DIR/cmdline-tools-extract"
  rm -rf "$extract_dir"
  mkdir -p "$extract_dir"
  unzip -q "$ZIP_PATH" -d "$extract_dir"
  rm -rf "$ANDROID_SDK_DIR/cmdline-tools/latest"
  mv "$extract_dir/cmdline-tools" "$ANDROID_SDK_DIR/cmdline-tools/latest"
fi

echo "==> Accepting SDK licenses and installing platform 37 + build-tools 37"
# pipefail would turn the expected SIGPIPE from `yes` into a failure, so scope it off here.
set +o pipefail
yes | "$SDKMANAGER" --sdk_root="$ANDROID_SDK_DIR" --licenses >/dev/null
set -o pipefail
"$SDKMANAGER" --sdk_root="$ANDROID_SDK_DIR" \
  "platform-tools" "platforms;android-37.0" "build-tools;37.0.0"

echo "==> Pointing the project at $ANDROID_SDK_DIR"
cat > "$REPO_DIR/local.properties" <<EOF
# Generated by dev-tools/setup-termux.sh; gitignored.
sdk.dir=$ANDROID_SDK_DIR
EOF

# AGP 9.4 downloads an x86-64 aapt2 that cannot run on an aarch64 Android host.
# Termux ships a native aarch64 build; use it for every Gradle invocation.
if [[ "$(uname -m)" == "aarch64" ]]; then
  mkdir -p "$(dirname "$GRADLE_PROPERTIES")"
  touch "$GRADLE_PROPERTIES"
  if ! grep -q '^android.aapt2FromMavenOverride=' "$GRADLE_PROPERTIES"; then
    cat >> "$GRADLE_PROPERTIES" <<EOF

# AGP's aapt2 binary is x86-64; use Termux's native aarch64 aapt2 instead.
android.aapt2FromMavenOverride=$PREFIX_DIR/bin/aapt2
android.sync.suppressAgpWarnings=UNSUPPORTED_PROJECT_OPTION_USE
EOF
  fi
fi

echo
echo "==> Done. Verify with:"
echo "    cd '$REPO_DIR'"
echo "    ./gradlew :app:testDebugUnitTest :app:assembleDebug"
